export function filterClientTrains(rawQuery) {
  if (!rawQuery) return [];
  const cleanTerm = String(rawQuery).replace(/^["']|["']$/g, '').trim();
  const normalized = cleanTerm.toLowerCase();
  if (!normalized) return [];

  const results = [];
  const seen = new Set();

  // 1. Check demo trains with verified route kilometrage
  for (const num of Object.keys(demoTrainMap)) {
    const t = demoTrainMap[num];
    const tNum = String(t.trainNumber).trim();
    const tNumLower = tNum.toLowerCase();
    const tNameLower = String(t.trainName).toLowerCase().trim();
    const fromLower = String(t.fromStation || '').toLowerCase().trim();
    const toLower = String(t.toStation || '').toLowerCase().trim();

    if (
      tNum === cleanTerm ||
      tNumLower === normalized ||
      tNumLower.includes(normalized) ||
      cleanTerm.includes(tNum) ||
      tNameLower.includes(normalized) ||
      fromLower.includes(normalized) ||
      toLower.includes(normalized)
    ) {
      seen.add(t.trainNumber);
      results.push(t);
    }
  }

  // 2. Check allTrains (1,160+ trains from timetable)
  for (const t of allTrains) {
    if (seen.has(t.trainNumber)) continue;
    const tNum = String(t.trainNumber).trim();
    const tNumLower = tNum.toLowerCase();
    const tNameLower = String(t.trainName || '').toLowerCase().trim();
    const fromLower = String(t.fromStation || '').toLowerCase().trim();
    const toLower = String(t.toStation || '').toLowerCase().trim();

    if (
      tNum === cleanTerm ||
      tNumLower === normalized ||
      tNumLower.includes(normalized) ||
      cleanTerm.includes(tNum) ||
      tNameLower.includes(normalized) ||
      fromLower.includes(normalized) ||
      toLower.includes(normalized)
    ) {
      seen.add(t.trainNumber);
      const start = t.fromStation || 'Start Station';
      const end = t.toStation || 'End Station';
      results.push({
        trainNumber: t.trainNumber,
        trainName: t.trainName || (start + ' to ' + end),
        fromStation: start,
        toStation: end,
        expectedPlatform: 1,
        departureTime: '08:00 AM',
        arrivalTime: '08:00 PM',
        duration: '12h 00m',
        fare: 1450,
        runningDays: ['S', 'M', 'T', 'W', 'T', 'F', 'S'],
        isNotRunningToday: false,
        stations: [
          { name: start, code: start.substring(0, 4).toUpperCase(), status: 'PASSED' },
          { name: end, code: end.substring(0, 4).toUpperCase(), status: 'DESTINATION' }
        ]
      });
      if (results.length >= 25) break;
    }
  }

  return results;
}
